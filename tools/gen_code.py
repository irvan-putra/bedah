comp_refs = {}

def kind_note(rp):
    if rp.endswith('AndroidManifest.xml'):
        return 'manifest'
    if '/res/layout/' in rp:
        return 'layout resource'
    if '/res/drawable' in rp:
        return 'drawable resource'
    if '/res/xml/' in rp:
        return 'xml resource'
    if rp.endswith('.json'):
        return 'data'
    if rp.endswith('.css'):
        return 'stylesheet'
    if rp.endswith('.html'):
        return 'page'
    if rp.endswith('.md'):
        return 'doc'
    if rp.endswith(('.gradle', '.properties')):
        return 'build config'
    if rp.endswith('.toml'):
        return 'config'
    if rp.endswith(('.yml', '.yaml')):
        return 'workflow config'
    if rp.endswith(('.png', '.jpg', '.webp')):
        return 'binary asset'
    if rp.endswith('.sh'):
        return 'shell script'
    return None

missing = []
for c in CONFIG:
    for f in c['files']:
        full = os.path.join(REPO, f)
        if not os.path.isfile(full):
            missing.append(f)
            continue
        if OUT_ABS and os.path.abspath(full) == OUT_ABS:
            # The generated file's self-size is measurable but excluded to
            # avoid self-reference: any count would describe the previous
            # generation.
            code_files[f] = dict(path=f, lines=None,
                                 role='generated - self-size excluded to avoid self-reference',
                                 els=[], kindNote=None, intraRefs=[])
            continue
        src = read(f)
        lines = src.count('\n') + (0 if src.endswith('\n') else 1)
        ds = decls(f, src)
        refs = file_refs(f, src)
        # intra-component refs attach to the file's elements (code view);
        # cross-component refs aggregate to COMPONENT_REFS (component view).
        intra = sorted({os.path.basename(t).rsplit('.', 1)[0]
                        for t, _v in refs if FILE2COMP.get(t) == c['id']})
        for t, via in refs:
            other = FILE2COMP.get(t)
            if other and other != c['id']:
                comp_refs.setdefault((c['id'], other), []).append(via)
        code_files[f] = dict(path=f, lines=lines, role=role_line(f, src),
                             els=[dict(name=n, kind=k) for n, k in ds],
                             kindNote=None if ds else kind_note(f),
                             intraRefs=[x for x in intra if x != os.path.basename(f).rsplit('.', 1)[0]])

if missing:
    raise SystemExit('CONFIG files missing from worktree: %s' % missing)

